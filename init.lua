--
-- Ctrl + Option + Cmd + R
------------------------------------------------------------

hs.hotkey.bind(
    MODIFIERS,
    "R",

    function()

        hs.alert.show(
            "Reloading Hammerspoon…",
            0.5
        )

        hs.timer.doAfter(
            0.2,

            function()
                hs.reload()
            end
        )

    end
)


