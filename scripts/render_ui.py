"""Render synthetic UI states without screen capture, permissions or clipboard access."""
import argparse
import os
import json
import subprocess
import sys
from pathlib import Path

os.environ["QT_QPA_PLATFORM"] = "offscreen"

from PySide6.QtCore import QEvent, QPoint, QTimer, Qt
from PySide6.QtGui import QColor, QImage, QPainter, QPalette, QPixmap
from PySide6.QtWidgets import QApplication, QToolButton

from ctrlcctrlv.review import ReviewResult
from ctrlcctrlv.settings import Settings
from ctrlcctrlv.syntax import syntax_hint
from ctrlcctrlv.ui import DiagnosticsDialog, Preview, SelectionOverlay, SettingsWindow
from scripts.generate_fixtures import generate
from scripts.render_ui_support import RenderSession


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path("artifacts/ui"))
    parser.add_argument("--compact", action="store_true", help="Проверить минимальный размер окон")
    parser.add_argument("--small-screen", action="store_true", help="Явная доступная логическая область 960×500; включает compact")
    parser.add_argument("--scale", type=float, choices=(1, 1.25, 1.5, 2), help="Qt scale factor; по умолчанию QT_SCALE_FACTOR или 1")
    parser.add_argument("--theme", choices=("light", "dark", "both"), default="both")
    parser.add_argument("--states", type=lambda text: text.split(','), help="Состояния через запятую; поддерживается *")
    parser.add_argument("--baseline", type=Path, default=Path('artifacts/ui-polish/before'), help="Каталог исходных кадров для metadata")
    parser.add_argument("--trace", action='store_true', help="Печатать проходы состояний; диагностика зависшего render")
    args = parser.parse_args()
    args.compact = args.compact or args.small_screen
    args.original_scale = os.environ.get('QT_SCALE_FACTOR')
    args.scale = args.scale if args.scale is not None else float(args.original_scale or 1)
    args.output.mkdir(parents=True, exist_ok=True)
    if args.theme == 'both':
        # Keep themes independent of previously created windows and palette
        # state, while retaining the original combined-manifest CLI contract.
        # Inspect original pixels: image-tool projections can omit small text.
        mode = 'compact-small-screen' if args.small_screen else 'compact' if args.compact else 'default'
        manifest_path = args.output / f'manifest-scale{round(args.scale * 100)}-{mode}.json'
        manifests = []
        for isolated_theme in ('light', 'dark'):
            subprocess.run([sys.executable, '-m', 'scripts.render_ui', *sys.argv[1:], '--theme', isolated_theme], check=True)
            manifests.append(json.loads(manifest_path.read_text(encoding='utf-8')))
        combined = manifests[0]
        combined['frames'] += manifests[1]['frames']
        combined['theme_process_isolation'] = True
        if manifests[0]['available_states'] != manifests[1]['available_states']:
            raise RuntimeError('Theme fixture coverage differs')
        manifest_path.write_text(json.dumps(combined, ensure_ascii=False, indent=2), encoding='utf-8')
        print(f'Combined isolated theme metadata: {manifest_path.resolve()}')
        return
    os.environ['QT_SCALE_FACTOR'] = str(args.scale)
    app = QApplication([])
    app.setQuitOnLastWindowClosed(False)
    session = RenderSession(app, args)
    fixtures = args.output / "fixtures"
    generate(fixtures)
    windows = []
    for dark in (False, True):
        theme = "dark" if dark else "light"
        if args.theme != 'both' and args.theme != theme:
            continue
        session.theme = theme
        palette = QPalette(app.palette())
        palette.setColor(QPalette.ColorRole.Window, QColor("#151a23" if dark else "#f5f7fa"))
        app.setPalette(palette)
        screen = app.primaryScreen()
        snapshot = QImage(screen.geometry().size(), QImage.Format.Format_RGB32)
        snapshot.fill(QColor('#202733' if dark else '#e4eaf3'))
        painter = QPainter(snapshot)
        painter.drawImage(20, 100, QImage(str(fixtures / f'python-{theme}-20.png')))
        painter.end()
        overlay = SelectionOverlay(screen, QPixmap.fromImage(snapshot))
        overlay.origin = QPoint(20, 100)
        overlay.position = QPoint(min(619, snapshot.width() - 21), min(351, snapshot.height() - 21))
        session.register(overlay)
        windows.append(overlay)
        overlay.show()
        app.processEvents()
        session.capture(overlay, 'selection', fit=False)
        overlay.hide()
        from ctrlcctrlv.ui import SetupWizard
        setup = SetupWizard()
        session.register(setup)
        windows.append(setup)
        setup.show()
        app.processEvents()
        session.capture(setup, 'setup')
        setup.hardware_toggle.setChecked(True)
        session.capture(setup, 'setup-hardware')
        setup.hardware_toggle.setChecked(False)
        setup.next()
        app.processEvents()
        session.capture(setup, 'setup-local')
        setup.back()
        setup.provider.setCurrentIndex(1)
        setup.next()
        app.processEvents()
        session.capture(setup, 'setup-cloud')
        setup.hide()
        settings = SettingsWindow(Settings())
        settings.update_model_states({"lightonocr-3-0.8b", "qwen3-vl-4b"}, {"lightonocr-3-0.8b"}, True, False)
        settings.install_button.hide()
        settings.work_model_info.setText("LightOnOCR-3 0.8B · готова")
        if args.compact:
            settings.resize(820, 620)
        settings.show_permissions({"screen": True, "accessibility": True, "input_monitoring": True})
        session.register(settings)
        settings.show()
        windows.append(settings)
        for page, name in enumerate(("work", "models", "configuration", "history")):
            if name == "history":
                settings.history_page.display([])
            settings.navigation.setCurrentRow(page)
            app.processEvents()
            session.capture(settings, name)
        from types import SimpleNamespace
        history_entry = SimpleNamespace(id=1, created="2026-10-12T00:00:00+00:00", kind="ocr", text="SELECT customer_id, total\nFROM orders;", model="LightOnOCR-3 0.8B", status="completed")
        settings.history_page.display([history_entry])
        app.processEvents()
        session.capture(settings, 'history-populated')
        settings.history_page.set_pins([history_entry])
        settings.history_page.display([history_entry])
        settings.history_page.set_undo_available(True)
        session.capture(settings, 'history-pins-undo')
        settings.history_page.show_history_error('Не удалось прочитать историю')
        session.capture(settings, 'history-error-undo')
        settings.history_page.clear_history_error()
        settings.history_page.set_undo_available(False)
        settings.history_page.search.setText('No matching record')
        settings.history_page.display([])
        session.capture(settings, 'history-search-empty')
        for tab, name in enumerate(("ocr", "typing", "system")):
            settings.show_configuration(name)
            app.processEvents()
            session.capture(settings, name)
        settings.capture_hotkey.start_recording()
        session.capture(settings, 'hotkey-recording')
        settings.capture_hotkey.finish_recording()
        settings.navigation.setCurrentRow(1)
        settings.set_model_queue(["qwen3-vl-4b", "qwen3-vl-8b"])
        settings.set_model_progress("qwen3-vl-4b", "weights.gguf", 750_000_000, 1_500_000_000)
        settings.set_busy(True)
        app.processEvents()
        session.capture(settings, 'model-download')
        settings.set_model_progress('qwen3-vl-4b', 'weights.gguf', 120_000_000, 0)
        session.capture(settings, 'model-queue-unknown-total')
        settings.clear_model_queue()
        settings.set_busy(False)
        settings.show_model_error('Загружено 1/4 · HTTP 503\nСинтетическая ошибка загрузки')
        settings.set_model_retry_available(True)
        session.capture(settings, 'model-error-retry')
        settings.clear_model_error()
        settings.runtime_toggle.setChecked(True)
        settings.hardware_info.setText("Windows AMD64\nRAM 63.9 ГБ\nNVIDIA GeForce RTX 3080 · свободно 8.8 ГБ\nОценка для выбранной модели: 2.2 ГБ; фактический расход зависит от контекста и снимка")
        settings.hardware_info.show()
        app.processEvents()
        session.capture(settings, 'hardware')
        settings.runtime_scroll.verticalScrollBar().setValue(settings.runtime_scroll.verticalScrollBar().maximum())
        session.capture(settings, 'hardware-details')
        settings.runtime_toggle.setChecked(False)
        settings.navigation.setCurrentRow(0)
        settings.status.setText("Не удалось подключиться к OCR. Буфер не изменён.")
        settings.show_operation_error("Не удалось подключиться к OCR.\nПроверьте соединение и выбранную модель.")
        settings.retry_button.show()
        app.processEvents()
        session.capture(settings, 'ocr-retry')
        settings.operation_error_toggle.setChecked(True)
        session.capture(settings, 'ocr-error-expanded')
        settings.retry_button.hide()
        settings.clear_operation_error()
        settings.status.setText("Распознавание… 7 с")
        settings.set_busy(True)
        settings.progress.setRange(0, 0)
        app.processEvents()
        session.capture(settings, 'ocr-slow')
        settings.set_busy(False)
        settings.status.clear()
        settings.show_configuration("ocr")
        settings.provider.setCurrentIndex(1)
        app.processEvents()
        session.capture(settings, 'cloud')
        settings.set_connection_state(True)
        session.capture(settings, 'cloud-connected')
        settings.edit_connection_key()
        session.capture(settings, 'cloud-key-edit')
        settings.set_connection_state(False)
        settings.remote_model.setText("example/vision-model")
        app.processEvents()
        session.capture(settings, 'pending')
        settings.navigation.setCurrentRow(0)
        settings.set_repeat_available(True)
        session.capture(settings, 'work-repeat-region')
        from dataclasses import replace
        from ctrlcctrlv.catalog import MODELS
        large_models = dict(MODELS)
        base_model = next(iter(MODELS.values()))
        for index in range(26):
            identifier = f'synthetic-vision-{index}'
            large_models[identifier] = replace(base_model, id=identifier,
                label=f'Синтетическая vision-модель {index + 1} с длинным именем · GGUF')
        large = SettingsWindow(Settings(), models=large_models)
        if args.compact:
            large.resize(820, 620)
        session.register(large)
        windows.append(large)
        large.navigation.setCurrentRow(1)
        large.runtime_toggle.setChecked(True)
        large.show()
        session.capture(large, 'models-30')
        large.toggle_all_models(0)
        large.set_model_queue(list(large_models)[4:7])
        large.set_model_progress('synthetic-vision-0', 'weights.gguf', 120_000_000, 820_000_000)
        large.show_model_error('Загружено 1/30 · HTTP 503\nСинтетическая ошибка загрузки')
        large.set_model_retry_available(True)
        session.capture(large, 'models-30-queue-error')
        large.hide()
        preview = Preview()
        preview.set_refine_models([("local", "qwen3-vl-4b", "Qwen3 VL 4B"),
                                   ("local", "qwen3-vl-8b", "Qwen3 VL 8B"),
                                   ("openrouter", "qwen/qwen3-vl-8b-instruct", "Qwen: Qwen3 VL 8B Instruct", "$0.25 / $0.75"),
                                   ("openrouter", "example/vision", "A model with a very long descriptive name and a specific revision for image understanding", "$0.15 / $0.60")])
        if args.compact:
            preview.resize(840, 620)
        session.register(preview)
        windows.append(preview)
        expected = (fixtures / f"python-{theme}-20.txt").read_text(encoding="utf-8")
        original = expected.replace("Hello,", "He11o,")
        preview.display(QImage(str(fixtures / f"python-{theme}-20.png")), original, 0.8, "Синтетический пример")
        app.processEvents()
        session.capture(preview, 'preview')
        preview.set_result_view('text')
        preview.open_search()
        preview.search_bar.query.setText('name')
        session.capture(preview, 'preview-search')
        preview.close_search()
        preview.set_raw_response('Синтетический исходный ответ OCR\n' + original)
        preview.show_raw_response()
        session.capture(preview.raw_dialog, 'raw-response', requested=(680, 440))
        preview.raw_dialog.close()
        preview.refine_model.set_installed({'qwen3-vl-4b'})
        chooser = preview.refine_model.create_chooser()
        windows.append(chooser)
        if args.compact:
            chooser.resize(640, 420)
        session.register(chooser)
        chooser.show()
        app.processEvents()
        session.capture(chooser, 'model-chooser')
        chooser.favorite.click()
        chooser.favorites_only.setChecked(True)
        session.capture(chooser, 'model-chooser-favorites')
        chooser.clear_filters()
        chooser.downloaded_only.setChecked(True)
        session.capture(chooser, 'model-chooser-downloaded')
        chooser.clear_filters()
        chooser.sources.setCurrentIndex(2)
        session.capture(chooser, 'model-chooser-cloud')
        chooser.clear_filters()
        chooser.search.setText('qwen3-vl-8b')
        session.capture(chooser, 'model-chooser-missing')
        chooser.search.setText("no matching model")
        app.processEvents()
        session.capture(chooser, 'model-chooser-empty')
        chooser.hide()
        preview.fit_image.setChecked(True)
        app.processEvents()
        session.capture(preview, 'preview-fitted')
        preview.fit_image.setChecked(False)
        preview.image_zoom.setValue(150)
        session.capture(preview, 'preview-zoom')
        preview.image_visible_action.setChecked(False)
        session.capture(preview, 'preview-image-hidden')
        preview.image_visible_action.setChecked(True)
        preview.propose(ReviewResult(original, expected, "checker", 2.7))
        if args.compact:
            preview.review_panel.resize(preview.review_panel.minimumSize())
        app.processEvents()
        session.capture(preview.review_panel, 'review')
        preview.review_panel.resize(720, 500)
        session.capture(preview.review_panel, 'review-narrow', requested=(720, 500))
        preview.review_choice_toggle.setChecked(True)
        session.capture(preview.review_panel, 'review-narrow-changes')
        preview.reject_review()
        preview.text.insertPlainText("# Ручная правка\n")
        preview.whitespace.setChecked(True)
        preview.wrap_text.setChecked(True)
        preview.font_size.setCurrentIndex(2)
        app.processEvents()
        session.capture(preview, 'edited')
        session.capture(preview, 'preview-text-manual')
        preview.set_review_busy(True)
        preview.review_panel.hide()
        preview.status.setText("Сверка текста со снимком…")
        app.processEvents()
        session.capture(preview, 'checking')
        preview.set_review_busy(False)
        preview.show_review_error('Недостаточно памяти GPU: доступно 4.0 ГБ, предварительная оценка для модели 4.9 ГБ.\nВыберите меньшую модель, CPU или OpenRouter.')
        session.capture(preview, 'preview-review-error')
        preview.show_review_error_details()
        session.capture(preview.review_error_dialog, 'preview-review-error-details')
        preview.review_error_dialog.close()
        preview.clear_review_error()
        preview.context_toggle.setChecked(True)
        app.processEvents()
        session.capture(preview, 'context')
        preview.review_context.setPlainText('Синтетический дополнительный промпт: сохраните ведущие нули и отступы.')
        preview.expand_prompt()
        session.capture(preview.prompt_dialog, 'prompt-expanded', requested=(640, 400))
        preview.prompt_dialog.reject()
        preview.context_toggle.setChecked(False)
        import csv
        import io
        rows = [["Товар", "Количество", "Цена, ₽", "Сумма, ₽"],
                ["Блокнот А5", "3", "149,90", "449,70"],
                ["Ручка «Синяя»", "12", "35,50", "426,00"],
                ["Папка, картонная", "2", "89,00", "178,00"],
                ["Бумага А4", "1", "520,00", "520,00"],
                ["Итого", "18", "", "1 573,70"]]
        csv_text = io.StringIO(newline="")
        csv.writer(csv_text, lineterminator="\n").writerows(rows)
        table_image = QImage(700, 228, QImage.Format.Format_RGB32)
        table_image.fill(QColor("#1b1e25" if dark else "#ffffff"))
        table_painter = QPainter(table_image)
        table_painter.setPen(QColor("#f0f2f6" if dark else "#202936"))
        for r, row in enumerate(rows):
            for col, value in enumerate(row):
                table_painter.drawText((12, 260, 410, 560)[col], r * 36 + 24, value)
        table_painter.end()
        preview.display(table_image, csv_text.getvalue(), .5, "LightOnOCR", format_mode="csv")
        app.processEvents()
        session.capture(preview, 'csv-preview')
        preview.set_result_view('table')
        preview.open_search()
        preview.search_bar.query.setText('Ручка')
        session.capture(preview, 'table-search')
        preview.close_search()
        preview.table.item(3, 2).setText("90,50")
        app.processEvents()
        session.capture(preview, 'csv-edited')
        preview.table.setCurrentCell(2, 1)
        preview.table.insert_rows(2)
        preview.table.insert_columns(1)
        preview.table.item(0, 1).setText('Код')
        preview.table.item(2, 0).setText('Новая строка 😀')
        preview.table.item(2, 1).setText('0012')
        preview.table.item(2, 2).setText('=SUM(1,2)')
        session.capture(preview, 'table-commands')
        session.capture_table_menu(preview.table)
        preview.set_result_view('text')
        session.capture(preview, 'csv-text-manual')
        preview.set_result_view('table')
        preview.display_history(csv_text.getvalue(), "LightOnOCR")
        app.processEvents()
        session.capture(preview, 'history-editor')
        from ctrlcctrlv.workspace_ui import AddModelDialog, OperationIndicator
        imported = AddModelDialog(settings)
        windows.append(imported)
        if args.compact:
            imported.resize(imported.minimumSizeHint().expandedTo(imported.minimumSize()))
        session.register(imported)
        imported.show()
        app.processEvents()
        session.capture(imported, 'add-model')
        imported.display(dict(weights=['very-long-model-name-' * 12 + '.gguf'],
                              projectors=['long-projector-name-' * 12 + '.gguf'], selected='',
                              repo='synthetic/vision-model', commit='a' * 40, license='MIT'))
        session.capture(imported, 'add-model-discovered')
        imported.advanced_toggle.setChecked(True)
        session.capture(imported, 'add-model-expanded')
        imported.hide()
        indicator = OperationIndicator()
        session.register(indicator)
        windows.append(indicator)
        indicator.display("OCR")
        app.processEvents()
        session.capture(indicator, 'indicator')
        indicator.hide()
        source = (fixtures / f"json-{theme}-20.txt").read_text(encoding="utf-8")
        broken = source.replace('"name": "Тест",', '"name": "Тест"')
        preview.display(QImage(str(fixtures / f"json-{theme}-20.png")), broken, 0.8, "Синтетический пример")
        preview.syntax_language.setCurrentIndex(preview.syntax_language.findData("json"))
        preview.show_syntax_hint(preview.syntax_revision, syntax_hint(broken, "json"))
        app.processEvents()
        session.capture(preview, 'syntax-warning')
        preview.display(QImage(), '', .0, 'Синтетический пустой результат')
        session.capture(preview, 'preview-empty')
        diagnostics = DiagnosticsDialog()
        diagnostics.display('{\n  "application": "0.1.0",\n  "system": "Windows",\n  "architecture": "AMD64",\n  "permissions": {\n    "accessibility": true,\n    "screen": true,\n    "input_monitoring": true\n  },\n  "ocr_runtime": {\n    "state": "stopped",\n    "ready": false\n  }\n}')
        session.register(diagnostics)
        windows.append(diagnostics)
        app.processEvents()
        session.capture(diagnostics, 'diagnostics')
        session.capture(diagnostics, 'diagnostics-collapsed')
        diagnostics.details_toggle.setChecked(True)
        session.capture(diagnostics, 'diagnostics-expanded')
        diagnostics.display('{}')
        session.capture(diagnostics, 'diagnostics-unknown')
        diagnostics.display('Синтетический повреждённый JSON')
        session.capture(diagnostics, 'diagnostics-error')
    def finish():
        for window in windows:
            window.close()
            window.deleteLater()
        app.sendPostedEvents(None, QEvent.Type.DeferredDelete)
        app.quit()
    QTimer.singleShot(100, finish)
    app.exec()
    manifest = session.finish()
    print(f"Rendered UI states in {args.output.resolve()}")
    print(f"Metadata: {manifest.resolve()}")


if __name__ == "__main__":
    main()
